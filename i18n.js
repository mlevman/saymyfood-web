(function(){
var LABEL={en:"EN",ru:"RU",es:"ES",pt:"PT"},D=window.SMF_I18N;
var btn=document.getElementById('lbtn'),menu=document.getElementById('lmenu'),cur=document.getElementById('lcur');
function apply(lang){
  var d=D[lang]||D.en;
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var v=d[el.getAttribute('data-i18n')];
    if(v!=null)el.innerHTML=v;
  });
  document.documentElement.lang=lang;
  if(cur)cur.textContent=LABEL[lang];
  if(menu)menu.querySelectorAll('button').forEach(function(b){b.classList.toggle('on',b.getAttribute('data-lang')===lang)});
  try{localStorage.setItem('smf_lang',lang)}catch(e){}
}
function pick(){
  var s=null;try{s=localStorage.getItem('smf_lang')}catch(e){}
  if(s&&D[s])return s;
  var n=(navigator.language||'en').slice(0,2).toLowerCase();
  return D[n]?n:'en';
}
function close(){menu.classList.remove('open');btn.setAttribute('aria-expanded','false')}
if(btn&&menu){
  btn.addEventListener('click',function(e){e.stopPropagation();var o=menu.classList.toggle('open');btn.setAttribute('aria-expanded',o?'true':'false')});
  menu.querySelectorAll('button').forEach(function(b){b.addEventListener('click',function(){apply(b.getAttribute('data-lang'));close()})});
  document.addEventListener('click',close);
  document.addEventListener('keydown',function(e){if(e.key==='Escape')close()});
}
apply(pick());
})();
